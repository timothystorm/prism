/**
 * Schema for an independently selectable parent or child shipment status.
 * Parsing does not expand parents into children or collapse child selections into parents.
 *
 * @example
 * const parent: Status = "LABEL_CREATED";
 * const child: Status = "LABEL_CREATED:WAITING_FOR_CARRIER_PICKUP";
 */
export const StatusSchema = z.union([ParentStatusSchema, SubStatusSchema]);

/**
 * Types for shipment status identifiers.
 */
export type ParentStatus = z.infer<typeof ParentStatusSchema>;
export type SubStatus = z.infer<typeof SubStatusSchema>;
export type Status = z.infer<typeof StatusSchema>;
